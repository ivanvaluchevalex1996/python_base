""" Задача
Напишите функцию reverse_tuple(), которая будет принимать список целых чисел. В результате выполнения этой функции будет получен кортеж уникальных элементов списка в обратном порядке. То есть сначала нужно инвертировать массив чисел, а потом оставить уникальные значения. """


def reverse_tuple(lst):
    data = lst[::-1]
    result = []
    for i in data:
        if i not in result:
            result.append(i)
    return tuple(result)
    

print(reverse_tuple([1, 3, 1, 4])) # -> (4, 1, 3)
reverse_tuple([1, 3, 4]) # -> (4, 3, 1)
