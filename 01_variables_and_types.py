# ЛОВУШКИ ДЛЯ ТЕХ, КТО ПРИШЁЛ С JS
# =============================================================================
#
# 1. нет var / let / const — просто name = value
# 2. True / False / None — с большой буквы    JS: true / false / null / undefined
# 3. and / or / not — словами, не && / || / !
# 4. elif — не else if
# 5. отступы обязательны, фигурных скобок { } нет
# 6. else: на том же уровне, что и if: (не как в JS внутри блока)
# 7. # — комментарий, не //
# 8. print() — не console.log()
# 9. input() — не prompt(); всегда возвращает строку!
# 10. / — обычное деление (3 / 2 = 1.5); // в Python — целочисленное деление
# 11. нет === и !== — только == и !=
# 12. int("3.14") — ❌ ValueError; сначала float(), потом int()
# 13. bool("0") — True (непустая строка); в JS Boolean("0") тоже true
# 14. bool([]) / bool("") — False; в JS пустой массив — truthy!
# 15. snake_case — принято в Python; camelCase — в JS
