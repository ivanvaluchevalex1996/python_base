# 🔴🔴🔴 УРОК 4: СТРОКИ (str)


# =============================================================================
# 1. ЧТО ТАКОЕ СТРОКА
# =============================================================================
#
# str — последовательность символов (текст).
# Ближайший аналог в JS — string.
#
# name = "Anna"
# city = 'Moscow'
#
# строка неизменяема (immutable) — нельзя заменить символ на месте:
# name[0] = "a"   # ❌ TypeError
#
# но можно создать новую строку:
# name = "a" + name[1:]   # "anna"
#
# пустая строка:
# s = ""
# bool("")   # False
# bool("hi") # True


# =============================================================================
# 2. СОЗДАНИЕ СТРОКИ
# =============================================================================
#
# одинарные или двойные кавычки — без разницы:
# s1 = "hello"
# s2 = 'hello'
#
# если внутри кавычки — используй другой тип:
# msg = "It's fine"
# path = 'He said "hi"'
#
# многострочная строка — тройные кавычки:
# text = """
# line 1
# line 2
# """
#
# из другого типа:
# str(42)        # "42"
# str(3.14)      # "3.14"
# str(True)      # "True"
# str([1, 2])    # "[1, 2]"
#
# input() всегда возвращает str:
# name = input("Ваше имя: ")


# =============================================================================
# 3. ДОСТУП К СИМВОЛАМ И СРЕЗЫ
# =============================================================================
#
# text = "Python"
#
# text[0]      # "P"          JS: text[0]
# text[-1]     # "n"          последний символ
# text[-2]     # "o"
#
# len(text)    # 6            JS: text.length
#
# срезы [start:stop:step] — stop НЕ включается (как у списков):
# text[0:3]    # "Pyt"        с 0 по 2
# text[:3]     # "Pyt"        с начала
# text[2:]     # "thon"       с 2 до конца
# text[::2]    # "Pto"        каждый второй
# text[::-1]   # "nohtyP"     развернуть
#
# text[100]    # ❌ IndexError — нет такого индекса


# =============================================================================
# 4. ОБЪЕДИНЕНИЕ И ПОВТОРЕНИЕ
# =============================================================================
#
# first = "Hello"
# second = "World"
#
# first + " " + second     # "Hello World"    JS: first + " " + second
# first += "!"             # "Hello!"         JS: first += "!"
#
# "-" * 10                 # "----------"     JS: "-".repeat(10)
# "ha" * 3                 # "hahaha"
#
# ⚠️ нельзя складывать str и int без преобразования:
# "age: " + 25             # ❌ TypeError
# "age: " + str(25)        # ✅ "age: 25"
# f"age: {25}"             # ✅ "age: 25"


