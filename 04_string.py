# =============================================================================
# JS → PYTHON: МЕТОДЫ СТРОК, КОТОРЫЕ ПУТАЮТ
# =============================================================================
#
# Если пришёл из JavaScript — здесь главные ловушки.
# Синтаксис часто похож, но поведение может отличаться.
#
#
# --- split() ---
#
# Python                          JavaScript
# -----------------------------------------------
# "a,b,c".split(",")              "a,b,c".split(",")     ← одинаково
# "a b".split(" ")                "a b".split(" ")       ← одинаково
#
# "  a   b  ".split()             "  a   b  ".split()
# # ['a', 'b']                    // ['  a   b  ']       ← РАЗНОЕ!
# # режет по любым пробелам,      // без аргумента почти
# # убирает лишние и по краям     // ничего не делает
#
# "hello".split("")               "hello".split("")
# # ValueError                    // ['h','e','l','l','o'] ← РАЗНОЕ!
# # пустой разделитель запрещён   // режет по символам
#
# "a   b".split(" ")              "a   b".split(" ")
# # ['a', '', '', 'b']            // ['a', '', '', 'b']   ← одинаково
# # каждый пробел = разделитель   // пустые строки в списке
#
# Задача «убрать лишние пробелы между словами»:
#   Python:     " ".join(a.split())
#   JavaScript: a.trim().split(/\s+/).join(' ')
#               или a.trim().replace(/\s+/g, ' ')
#
#
# --- join() — аргументы «наоборот» ---
#
# Python                          JavaScript
# -----------------------------------------------
# " ".join(['a', 'b'])            ['a', 'b'].join(' ')
# # строка вызывает join          # массив вызывает join
# # разделитель — объект метода   # разделитель — аргумент
#
# "".join(['a', 'b'])             ['a', 'b'].join('')
# # 'ab'                          // 'ab'
#
# " ".join(['a', 'b'])            ['a', 'b'].join(' ')
# # 'a b'                         // 'a b'
#
#
# --- strip / trim ---
#
# Python                          JavaScript
# -----------------------------------------------
# s.strip()                       s.trim()           ← убрать пробелы по краям
# s.lstrip()                      s.trimStart()
# s.rstrip()                      s.trimEnd()
#
# "  hi  ".strip()                "  hi  ".trim()
# # 'hi'                          // 'hi'
#
# strip НЕ убирает лишние пробелы ВНУТРИ строки — только по краям.
#
#
# --- len vs length ---
#
# Python:  len("hello")     # 5
# JS:      "hello".length    // 5
#
#
# --- регистр ---
#
# Python                          JavaScript
# -----------------------------------------------
# s.upper()                       s.toUpperCase()
# s.lower()                       s.toLowerCase()
# s.capitalize()                  s[0].toUpperCase() + s.slice(1)
# s.title()                       нет прямого аналога
#
#
# --- поиск подстроки ---
#
# Python                          JavaScript
# -----------------------------------------------
# "abc".find("b")                 "abc".indexOf("b")     # 1
# "abc".find("x")                 "abc".indexOf("x")     # -1 / -1
# # -1 если не найдено            // -1 если не найдено
#
# "abc".index("x")                "abc".indexOf("x")
# # ValueError если нет           // -1
#
# "b" in "abc"                    "abc".includes("b")    # True
# "x" in "abc"                    "abc".includes("x")      # False
#
#
# --- начало / конец строки ---
#
# Python                          JavaScript
# -----------------------------------------------
# s.startswith("hi")              s.startsWith("hi")
# s.endswith("!")                 s.endsWith("!")
#
#
# --- replace ---
#
# Python                          JavaScript
# -----------------------------------------------
# s.replace("a", "b")             s.replace("a", "b")    ← похоже
# s.replace("a", "b", 1)           s.replace("a", "b")    ← только 1-е вхождение
#                                 s.replaceAll("a", "b") ← все вхождения (ES2021)
#
# "aaa".replace("a", "b")         "aaa".replace("a", "b")
# # 'bbb'                         // 'baa'  ← РАЗНОЕ! JS меняет только 1 раз
#
#
# --- срезы vs slice/substring ---
#
# Python:  s[1:4]       # символы с 1 по 3
#          s[::-1]      # развернуть строку
# JS:      s.slice(1, 4)
#          s.split('').reverse().join('')   или [...s].reverse().join('')
#
#
# --- проверка типа ---
#
# Python:  isinstance(x, str)
# JS:      typeof x === "string"
#
#
# --- f-строки vs template literals ---
#
# Python:  name = "Anna"; f"Hello, {name}!"
# JS:      const name = "Anna"; `Hello, ${name}!`
#
#
# --- ШПАРГАЛКА: частые ошибки при переходе JS → Python ---
#
# ❌ " ".join(a.split(""))        → ValueError (в JS split("") режет по символам)
# ❌ a.split(" ") для задачи       → пустые '' в списке, лишние пробелы останутся
# ❌ " ".join(arr)                 → в Python join у строки, не у списка
# ❌ arr.join(" ")                 → в Python так нельзя, только в JS
# ❌ s.trim()                      → в Python это s.strip()
# ❌ s.length                      → в Python это len(s)
# ❌ s.includes("x")               → в Python это "x" in s
#
# ✅ " ".join(a.split())           → убрать лишние пробелы между словами
# ✅ a.strip()                     → убрать пробелы по краям
# ✅ "x" in s                      → проверить подстроку
# ✅ s.replace("a", "b")           → помнить: меняет ВСЕ вхождения (не как JS)
    
