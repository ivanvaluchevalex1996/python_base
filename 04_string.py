# 15. ЛОВУШКИ ДЛЯ ТЕХ, КТО ПРИШЁЛ С JS
# =============================================================================
#
# 1. строка неизменяема — s[0] = "x" нельзя; методы возвращают новую строку
# 2. "age: " + 25 — ❌ TypeError; нужен str(25) или f-string
# 3. text.length → len(text)
# 4. text.includes("x") → "x" in text
# 5. text.startsWith / endsWith → startswith / endswith (snake_case!)
# 6. arr.join(",") → ",".join(arr)  — join у разделителя, не у списка
# 7. text.trim() → text.strip()
# 8. text.indexOf() → find() (или index() с ошибкой)
# 9. template literals `...` → f"..."
# 10. одинарные ' и двойные " — одинаковы (в JS тоже)
# 11. input() всегда str — int(input()) для числа
# 12. срез text[1:4] — stop не включается (как slice в JS)
# 13. нет charAt — используй text[i] или text[i:i+1]


