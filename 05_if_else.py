# =============================================================================
# 5. ОПЕРАТОРЫ СРАВНЕНИЯ
# =============================================================================
#
# ==   равно              JS: ===
# !=   не равно           JS: !==
# <    меньше
# >    больше
# <=   меньше или равно
# >=   больше или равно
#
# a = 10
# b = 20
# a == b    # False
# a != b    # True
# a < b     # True
# a >= 10   # True
#
# сравнение строк — посимвольно (лексикографически):
# "apple" < "banana"   # True
# "A" < "a"            # True (заглавные буквы «меньше» строчных в ASCII)
#
# цепочка сравнений — удобная фишка Python (в JS так нельзя):
# age = 25
# if 18 <= age < 65:
#     print("Трудоспособный возраст")
# # JS: if (age >= 18 && age < 65) {}


# =============================================================================
# 6. ЛОГИЧЕСКИЕ ОПЕРАТОРЫ: AND, OR, NOT
# =============================================================================
#
# and   — оба условия True          JS: &&
# or    — хотя бы одно True         JS: ||
# not   — инверсия                  JS: !
#
# age = 20
# has_ticket = True
#
# if age >= 18 and has_ticket:
#     print("Пускаем в кино")
#
# if age < 12 or age >= 65:
#     print("Скидка")
#
# is_raining = False
# if not is_raining:
#     print("Можно гулять")
#
# приоритет: not → and → or
# скобки помогают, когда логика сложная:
# if (a or b) and c:
#     ...


# =============================================================================
# 7. TRUTHY И FALSY — ЧТО СЧИТАЕТСЯ True / False
# =============================================================================
#
# В if можно передать не только True/False, но и любое значение.
# Python сам решает, «истинное» оно или «ложное».
#
# FALSY (считаются False):
# False
# 0, 0.0
# ""           — пустая строка
# []           — пустой список
# {}           — пустой словарь
# set()        — пустое множество
# None
#
# всё остальное — TRUTHY (True):
# True
# 42, -1, 3.14
# "hello", "0", " "
# [1, 2], {"a": 1}
#
# name = ""
# if name:
#     print("Привет,", name)
# else:
#     print("Имя не указано")   # сработает это
#
# items = [1, 2, 3]
# if items:
#     print("Список не пустой")
#
# ⚠️ bool("0")  → True  (непустая строка!)
# ⚠️ bool([])   → False, но в JS пустой массив [] — truthy!


# =============================================================================
