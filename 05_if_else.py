# =============================================================================
# 13. ЛОВУШКИ ДЛЯ ТЕХ, КТО ПРИШЁЛ С JS
# =============================================================================
#
# Python                          JavaScript
# -----------------------------------------------
# if x > 0:                       if (x > 0) {
#     print(x)                        console.log(x);
#                                 }
#
# elif                            else if
# and / or / not                  && / || / !
# == / !=                         === / !==
# True / False                    true / false
# 18 <= age < 65                  age >= 18 && age < 65
# "да" if x else "нет"            x ? "да" : "нет"
# "x" in arr                      arr.includes("x")
# pass                            // пустой блок {} допустим
#
# --- частые ошибки ---
#
# ❌ if x > 0: print(x)   без отступа на следующей строке — SyntaxError
# ❌ else if x > 0:       → нужно elif
# ❌ if age = 18:        → присваивание =, нужно сравнение ==
# ❌ if age == "18":     → input() вернул строку, а ты сравниваешь с числом без int()
# ❌ if x == True:       → лучше if x: (если x уже bool) или if x is True (редко нужно)
# ❌ if not x == 5:      → читается плохо; лучше if x != 5:
# ❌ путать is и ==:
#    a = [1, 2]; b = [1, 2]
#    a == b   # True  (одинаковое содержимое)
#    a is b   # False (разные объекты в памяти)
#    is — для None, True, False: if x is None:
#
# ✅ отступы — 4 пробела (или Tab, но не смешивай!)
# ✅ else: на уровне if:, не внутри блока if
# ✅ цепочка: if → elif → elif → else (только один блок выполнится)


